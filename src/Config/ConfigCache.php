<?php

declare(strict_types=1);

namespace VeyroPHP\Config;

use RuntimeException;
use VeyroPHP\Config\Exception\ConfigException;

/**
 * The configuration as one generated PHP file (bootstrap/cache/config.php).
 *
 * Without it, every request reads .env and every config/*.php file. With it,
 * one file is loaded, which opcache keeps in memory. The file contains every
 * config value, including secrets from .env, so it must stay outside the web
 * root, like .env itself.
 */
final class ConfigCache
{
    public const RELATIVE_PATH = 'bootstrap/cache/config.php';

    /**
     * The cached items, or null when there is no (valid) cache file.
     *
     * @return array<string, mixed>|null
     */
    public static function read(string $path): ?array
    {
        if (!is_file($path)) {
            return null;
        }

        $items = (static fn(string $__path): mixed => require $__path)($path);

        if (!is_array($items)) {
            return null;
        }

        /** @var array<string, mixed> $items */
        return $items;
    }

    /**
     * Writes the cache file atomically (temporary file, then rename).
     *
     * @throws ConfigException when a value cannot be cached (closure, object, resource)
     * @throws RuntimeException when the file cannot be written
     */
    public static function write(Config $config, string $path): void
    {
        $items = $config->all();
        self::assertCacheable($items, '');

        $code = "<?php\n\n// Generated by \"php veyro config:cache\". Do not edit; run \"php veyro config:clear\" instead.\n\nreturn "
            . var_export($items, true) . ";\n";

        $directory = dirname($path);
        if (!is_dir($directory) && !@mkdir($directory, 0775, true) && !is_dir($directory)) {
            throw new RuntimeException(sprintf('Cannot create directory %s.', $directory));
        }

        $temporary = $path . '.' . bin2hex(random_bytes(6)) . '.tmp';
        if (@file_put_contents($temporary, $code, LOCK_EX) !== strlen($code) || !@rename($temporary, $path)) {
            @unlink($temporary);

            throw new RuntimeException(sprintf('Cannot write %s.', $path));
        }

        if (function_exists('opcache_invalidate')) {
            @opcache_invalidate($path, true);
        }
    }

    public static function clear(string $path): bool
    {
        if (!is_file($path)) {
            return false;
        }

        @unlink($path);
        if (function_exists('opcache_invalidate')) {
            @opcache_invalidate($path, true);
        }

        return !is_file($path);
    }

    private static function assertCacheable(mixed $value, string $key): void
    {
        if (is_array($value)) {
            foreach ($value as $name => $item) {
                self::assertCacheable($item, $key === '' ? (string) $name : $key . '.' . $name);
            }

            return;
        }

        if ($value !== null && !is_scalar($value)) {
            throw ConfigException::notCacheable($key, $value);
        }
    }
}
